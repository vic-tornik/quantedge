CREATE TABLE IF NOT EXISTS qe_market_events(
 scope TEXT NOT NULL, id BIGINT NOT NULL, symbol TEXT NOT NULL, update_id TEXT NOT NULL,
 bid NUMERIC NOT NULL, ask NUMERIC NOT NULL, received DOUBLE PRECISION NOT NULL,
 PRIMARY KEY(scope,id));
CREATE TABLE IF NOT EXISTS qe_orders(
 scope TEXT NOT NULL, id TEXT NOT NULL, symbol TEXT NOT NULL, side TEXT NOT NULL,
 qty NUMERIC NOT NULL, price NUMERIC NOT NULL, created BIGINT NOT NULL, sent BIGINT,
 status TEXT NOT NULL, receipt TEXT, PRIMARY KEY(scope,id));
CREATE TABLE IF NOT EXISTS qe_fills(
 scope TEXT NOT NULL, id TEXT NOT NULL, ticket TEXT NOT NULL, symbol TEXT NOT NULL, side TEXT NOT NULL,
 qty NUMERIC NOT NULL, quote_qty NUMERIC NOT NULL, commission NUMERIC NOT NULL,
 commission_asset TEXT NOT NULL, ts BIGINT NOT NULL, PRIMARY KEY(scope,id));
CREATE TABLE IF NOT EXISTS qe_snapshots(
 scope TEXT NOT NULL, id BIGINT NOT NULL, received DOUBLE PRECISION NOT NULL, payload JSONB NOT NULL,
 PRIMARY KEY(scope,id));
CREATE TABLE IF NOT EXISTS qe_balances(
 scope TEXT NOT NULL, snapshot_id BIGINT NOT NULL, asset TEXT NOT NULL, quantity NUMERIC NOT NULL,
 PRIMARY KEY(scope,snapshot_id,asset));
CREATE TABLE IF NOT EXISTS qe_cursors(scope TEXT PRIMARY KEY,event_id BIGINT NOT NULL,snapshot_id BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS qe_depth_events(
 scope TEXT NOT NULL,id BIGINT NOT NULL,symbol TEXT NOT NULL,kind TEXT NOT NULL,
 received DOUBLE PRECISION NOT NULL,payload JSONB NOT NULL,PRIMARY KEY(scope,id));
CREATE TABLE IF NOT EXISTS qe_depth_cursors(scope TEXT PRIMARY KEY,event_id BIGINT NOT NULL);
